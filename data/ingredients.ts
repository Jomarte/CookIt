export function getIngredientSuggestions(text: string, lang: 'pt' | 'en' = 'pt'): IngredientEntry[] {
  if (!text.trim() || text.length < 1) return [];
  const lower = text.toLowerCase();

  if (lang === 'en') {
    const startsWith = CANONICAL_INGREDIENTS.filter(i =>
      (i.nameEn ?? i.name).toLowerCase().startsWith(lower)
    );
    const contains = CANONICAL_INGREDIENTS.filter(i =>
      !(i.nameEn ?? i.name).toLowerCase().startsWith(lower) &&
      (i.nameEn ?? i.name).toLowerCase().includes(lower)
    );
    return [...startsWith, ...contains].slice(0, 5).map(i => ({
      name: i.nameEn ?? i.name,
      category: i.categoryEn ?? i.category,
      nameEn: i.nameEn,
      categoryEn: i.categoryEn,
    }));
  }

  const startsWith = CANONICAL_INGREDIENTS.filter(i =>
    i.name.toLowerCase().startsWith(lower)
  );
  const contains = CANONICAL_INGREDIENTS.filter(i =>
    !i.name.toLowerCase().startsWith(lower) &&
    i.name.toLowerCase().includes(lower)
  );
  return [...startsWith, ...contains].slice(0, 5);
}
